#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any


def safe_remove(path: Path) -> None:
    try:
        if path.exists():
            path.unlink()
    except OSError:
        pass


def local_or_path_command(name: str) -> str:
    local = Path(__file__).resolve().parent / name
    if local.exists():
        if not os.access(local, os.X_OK):
            local.chmod(local.stat().st_mode | 0o755)
        return str(local)
    return name


def chgsum(work_path: Path, file1: str, file2: str, fact1: float = 1.0, fact2: float = 1.0) -> None:
    """Sum two CHGCAR-format files (replaces chgsum.pl, no Perl dependency)."""
    path1, path2 = work_path / file1, work_path / file2

    def read_header(fh):
        header_lines = [fh.readline() for _ in range(5)]
        line6 = fh.readline()
        header_lines.append(line6)
        tokens = line6.split()
        if tokens[0].isdigit():
            atoms = tokens
        else:
            atoms_line = fh.readline()
            header_lines.append(atoms_line)
            atoms = atoms_line.split()
        n_atoms = sum(int(x) for x in atoms)
        for _ in range(n_atoms + 2):
            header_lines.append(fh.readline())
        grid_line = fh.readline()
        header_lines.append(grid_line)
        gx, gy, gz = (int(x) for x in grid_line.split())
        return header_lines, gx * gy * gz

    with open(path1) as f1, open(path2) as f2:
        header, n_points1 = read_header(f1)
        _, n_points2 = read_header(f2)
        if n_points1 != n_points2:
            raise RuntimeError(f"Grid point count mismatch: {n_points1} vs {n_points2}")

        out_path = work_path / "CHGCAR_sum"
        with open(out_path, "w") as out:
            out.writelines(header)
            n_lines = (n_points1 + 4) // 5
            for _ in range(n_lines):
                vals1 = f1.readline().split()
                vals2 = f2.readline().split()
                merged = [fact1 * float(a) + fact2 * float(b) for a, b in zip(vals1, vals2, strict=True)]
                out.write(" " + " ".join(f"{v:18.11E}" for v in merged) + "\n")


def cluster_by_charge(element_atoms: dict[str, list[dict[str, Any]]], threshold: float = 0.05) -> list[dict[str, Any]]:
    """Group atoms of the same element by similar net_charge."""
    groups: list[dict[str, Any]] = []
    for element, atoms in element_atoms.items():
        sorted_atoms = sorted(atoms, key=lambda a: a["net_charge"])
        cluster: list[dict[str, Any]] = [sorted_atoms[0]]
        for atom in sorted_atoms[1:]:
            if abs(atom["net_charge"] - cluster[-1]["net_charge"]) <= threshold:
                cluster.append(atom)
            else:
                groups.append(summarize_cluster(element, cluster))
                cluster = [atom]
        groups.append(summarize_cluster(element, cluster))
    return groups


def summarize_cluster(element: str, cluster: list[dict[str, Any]]) -> dict[str, Any]:
    charges = [a["net_charge"] for a in cluster]
    return {
        "element": element,
        "count": len(cluster),
        "avg_net_charge": round(sum(charges) / len(charges), 4),
        "min_net_charge": round(min(charges), 4),
        "max_net_charge": round(max(charges), 4),
        "atom_indices": [a["atom_index"] for a in cluster],
    }


def analyze_bader_charge(
    work_dir: str,
    bader_cmd: str | None = None,
) -> dict[str, Any]:
    work_path = Path(work_dir).resolve()
    if not work_path.is_dir():
        return {"status": "missing_inputs", "message": f"Directory does not exist: {work_path}"}

    required_files = ["CHGCAR", "AECCAR0", "AECCAR2", "POTCAR", "POSCAR"]
    for filename in required_files:
        if not (work_path / filename).exists():
            return {"status": "missing_inputs", "message": f"Required file missing in {work_path}: {filename}"}

    bader_cmd = bader_cmd or local_or_path_command("bader")

    try:
        safe_remove(work_path / "CHGCAR_sum")
        safe_remove(work_path / "ACF.dat")

        chgsum(work_path, "AECCAR0", "AECCAR2")
        chgcar_sum_path = work_path / "CHGCAR_sum"
        if not chgcar_sum_path.exists():
            return {"status": "error", "message": "CHGCAR_sum was not generated by chgsum."}

        bader_process = subprocess.run(
            [bader_cmd, "CHGCAR", "-ref", "CHGCAR_sum"],
            capture_output=True,
            text=True,
            cwd=work_path,
            check=False,
        )
        acf_path = work_path / "ACF.dat"
        if bader_process.returncode != 0 or not acf_path.exists():
            stderr = (bader_process.stderr or "").strip()
            stdout = (bader_process.stdout or "").strip()
            detail = stderr or stdout or f"return code = {bader_process.returncode}"
            return {"status": "error", "message": f"bader failed or ACF.dat was not generated.\nError: {detail}"}

        zval_by_index: dict[int, float] = {}
        potcar_elements: list[str] = []
        potcar_zval_pattern = re.compile(r"ZVAL\s*=\s*([0-9.]+)")
        with open(work_path / "POTCAR", encoding="utf-8", errors="ignore") as fh:
            for line in fh:
                if "TITEL" in line:
                    parts = line.split()
                    if len(parts) >= 4:
                        potcar_elements.append(parts[3].split("_")[0])
                if "ZVAL" in line:
                    match = potcar_zval_pattern.search(line)
                    if match:
                        current_element_idx = len(potcar_elements) - 1
                        if current_element_idx >= 0 and current_element_idx not in zval_by_index:
                            zval_by_index[current_element_idx] = float(match.group(1))

        with open(work_path / "POSCAR", encoding="utf-8", errors="ignore") as fh:
            lines = fh.readlines()
        if len(lines) < 7:
            return {
                "status": "error",
                "message": "POSCAR format is incomplete; elements and atom counts cannot be read.",
            }
        elements = lines[5].strip().split()
        counts = [int(x) for x in lines[6].strip().split()]

        atom_mapping: list[dict[str, Any]] = []
        for idx, (element, count) in enumerate(zip(elements, counts, strict=True)):
            if idx not in zval_by_index:
                return {"status": "error", "message": "Element mapping between POSCAR and POTCAR is inconsistent."}
            for _ in range(count):
                atom_mapping.append({"element": element, "zval": zval_by_index[idx]})

        atom_details: list[dict[str, Any]] = []
        with open(acf_path, encoding="utf-8", errors="ignore") as fh:
            acf_lines = fh.readlines()
        data_lines = acf_lines[2:-4]
        for i, line in enumerate(data_lines):
            parts = line.strip().split()
            if len(parts) < 5 or i >= len(atom_mapping):
                continue
            atom_index = int(parts[0])
            x, y, z = float(parts[1]), float(parts[2]), float(parts[3])
            bader_charge = float(parts[4])
            atom_info = atom_mapping[i]
            zval = float(atom_info["zval"])
            net_charge = zval - bader_charge
            atom_details.append(
                {
                    "atom_index": atom_index,
                    "element": atom_info["element"],
                    "coordinates": [x, y, z],
                    "zval": zval,
                    "bader_charge": bader_charge,
                    "net_charge": round(net_charge, 4),
                }
            )

        per_element: dict[str, float] = {}
        total_net_charge = 0.0
        element_atoms: dict[str, list[dict[str, Any]]] = {}
        for item in atom_details:
            net_charge = float(item["net_charge"])
            total_net_charge += net_charge
            element = str(item["element"])
            per_element[element] = round(per_element.get(element, 0.0) + net_charge, 4)
            element_atoms.setdefault(element, []).append(item)

        charge_groups = cluster_by_charge(element_atoms)

        return {
            "status": "success",
            "message": "Bader charge analysis completed successfully.",
            "total_atoms": len(atom_details),
            "total_net_charge": round(total_net_charge, 4),
            "per_element_net_charge": per_element or None,
            "charge_groups": charge_groups,
            "atom_details": atom_details or None,
        }
    except Exception as exc:
        return {"status": "error", "message": f"Exception during Python-side parsing: {exc}"}


def format_summary(result: dict[str, Any]) -> str:
    lines = [f"Bader analysis: {result['total_atoms']} atoms, total net charge: {result['total_net_charge']:+.4f} e"]
    per_elem = result.get("per_element_net_charge")
    if per_elem:
        entries = ", ".join(f"{el}: {q:+.4f} e" for el, q in per_elem.items())
        lines.append(f"Per-element net charge: {entries}")
    for g in result.get("charge_groups", []):
        idx_str = ",".join(str(i) for i in g["atom_indices"])
        if g["count"] == 1:
            lines.append(f"  {g['element']} x{g['count']} (#{idx_str}): {g['avg_net_charge']:+.4f} e")
        else:
            lines.append(
                f"  {g['element']} x{g['count']} (#{idx_str}): avg {g['avg_net_charge']:+.4f} e  [{g['min_net_charge']:+.4f}, {g['max_net_charge']:+.4f}]"
            )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Analyze Bader charge distribution for a VASP work directory.")
    parser.add_argument(
        "--work-dir", required=True, help="Directory containing CHGCAR, AECCAR0, AECCAR2, POTCAR, POSCAR."
    )
    parser.add_argument("--bader-cmd", default=None, help="Optional bader executable path or command.")
    parser.add_argument("--json", action="store_true", help="Print a single compact JSON object to stdout.")
    args = parser.parse_args()

    try:
        result = analyze_bader_charge(args.work_dir, bader_cmd=args.bader_cmd)
        if result.get("status") != "success":
            raise RuntimeError(result.get("message", "Bader charge analysis failed"))
        if args.json:
            print(json.dumps(result, separators=(",", ":"), ensure_ascii=False))
        else:
            print(format_summary(result))
            print(json.dumps(result, indent=2, ensure_ascii=False))
    except Exception as e:
        error_result = {"status": "error", "message": str(e)}
        if args.json:
            print(json.dumps(error_result, separators=(",", ":"), ensure_ascii=False))
        else:
            print(f"Error: {e}", file=sys.stderr)
        raise


if __name__ == "__main__":
    main()
