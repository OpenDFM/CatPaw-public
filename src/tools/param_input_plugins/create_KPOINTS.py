from pymatgen.core import Structure

# Internal constant: N*a density factor (not exposed externally).
# k_i = max(1, round(_BASE_K_DENSITY / a_i))
# Example: a=5 A -> k=round(20/5)=4
BASE_K_DENSITY = 20.0

# DOS-density multiplier: for dos_calc, k-point density = _BASE_K_DENSITY * 2.5 = 50
DOS_K_DENSITY_MULTIPLIER = 2.5


def generate_smart_kpoints(
    poscar_path: str, task_type: str = None, custom_grid: list = None, output_path: str = "KPOINTS"
) -> str:
    """
    Generate KPOINTS from lattice constants, detect vacuum directions, and enforce K=1 there.
    Supports ParamWorker-enforced override via custom_grid.
    For task_type="dos_calc", the k-point density is increased by 2.5x.
    """
    try:
        if custom_grid and isinstance(custom_grid, list) and len(custom_grid) == 3:
            k_mesh = custom_grid
            msg_prefix = "ParamWorker-enforced override"

        # Otherwise use automatic generation.
        else:
            struct = Structure.from_file(poscar_path)
            lattice_lengths = struct.lattice.abc

            # DOS densification: 2.5x when task_type is dos_calc.
            if task_type == "dos_calc":
                actual_density = BASE_K_DENSITY * DOS_K_DENSITY_MULTIPLIER
                density_tag = f"DOS densified (k={actual_density:.0f}/a)"
            else:
                actual_density = BASE_K_DENSITY
                density_tag = f"k={BASE_K_DENSITY:.0f}/a"

            k_mesh = []
            for length in lattice_lengths:
                # Physical rule: enforce K=1 along directions with large vacuum.
                if length > 15.0:
                    k_mesh.append(1)
                else:
                    k = max(1, int(actual_density / length + 0.5))
                    k_mesh.append(k)

            msg_prefix = f"Automatically generated ({density_tag})"

        # Write KPOINTS (Gamma-centered by default; robust across crystal systems).
        with open(output_path, "w", encoding="utf-8") as f:
            f.write("K-Auto generated by Agent\n")
            f.write("0\n")
            f.write("Gamma\n")
            f.write(f"{k_mesh[0]} {k_mesh[1]} {k_mesh[2]}\n")
            f.write("0 0 0\n")

        return f"KPOINTS generated successfully ({msg_prefix}); grid = {k_mesh}; saved to {output_path}."

    except Exception as e:
        return f"KPOINTS generation failed: {str(e)}"
